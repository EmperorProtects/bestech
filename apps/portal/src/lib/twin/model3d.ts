/**
 * Раскладка 3D-модели молочного комплекса для вьюера на three.js. Единицы — метры:
 * X вдоль осей 1→7 (шаг 6 м, 36 м), Z вдоль осей А→Г (шаг 6 м, пролёт 18 м), Y вверх.
 * Модуль без серверных зависимостей: его импортирует клиентский вьюер.
 *
 * Когда подключится IFC-модель (web-ifc), координаты датчиков будут браться из неё;
 * до тех пор они заданы здесь по привязке из реестра датчиков (оси и отметки).
 */

export const BUILDING = {
  length: 36,
  span: 18,
  bay: 6,
  /** Отметка низа ферм, +7.200. */
  eave: 7.2,
  /** Конёк. */
  ridge: 10,
} as const;

export const AXES_X = ['1', '2', '3', '4', '5', '6', '7'];
export const AXES_Z = ['А', 'Б', 'В', 'Г'];

export type Vec3 = [number, number, number];

/** Положение датчиков объекта 2026-014 по их привязке (ось, отметка). */
const SENSOR_POSITIONS: Record<string, Vec3> = {
  'КЖ-1': [1.5, 0.35, 1.5], // ось А/1, монолит перекрытия
  'КЖ-3': [18, 0.35, 6], // ось Б/4
  'ПР-3': [19.6, 0.35, 7.4], // датчик зрелости рядом с КЖ-3
  'ГМ-01': [-0.8, 0.35, -0.8], // марка у колонны А/1
  'ГМ-03': [30, 0.35, 6], // ось Б/6
  'ГМ-07': [6, 0.35, 12], // ось В/2
  'Ф-1': [6, BUILDING.eave, 9], // ферма по оси 2
  'Ф-2': [24, BUILDING.eave, 9], // ферма по оси 5 (пролёт 4–5)
  'Ф-3': [30, BUILDING.eave, 9], // ферма по оси 6
  'ТР-1': [16, 2.6, 18.25], // стена по оси Г, между осями 3 и 4 (не перекрывает метку фермы Ф-1)
  'ВК-У2': [21, 0.6, -3.5], // узел водоснабжения на вводе
  'ЭОМ-ТП': [-5, 1.2, 3], // трансформаторная подстанция у оси А/1
};

/** Какую ферму подсвечивать по состоянию датчика нагрузки: код датчика → ось X фермы. */
export const TRUSS_OF_SENSOR: Record<string, number> = {
  'Ф-1': 6,
  'Ф-2': 24,
  'Ф-3': 30,
};

/** Позиция датчика; незнакомые коды выстраиваются рядом с корпусом, чтобы не потеряться. */
export function sensorPosition(code: string, index: number): Vec3 {
  return SENSOR_POSITIONS[code] ?? [2 + (index % 7) * 5, 0.8, BUILDING.span + 5 + Math.floor(index / 7) * 3];
}

/** Высота верхнего пояса фермы в точке пролёта z (двускатная кровля). */
export function roofHeightAt(z: number): number {
  const half = BUILDING.span / 2;
  return BUILDING.eave + (BUILDING.ridge - BUILDING.eave) * (1 - Math.abs(z - half) / half);
}
